def blocked_by_doc_root(word):
    """候选词是否以公文词根开头 —— 是则一定不是人名。

    只挡「词根 + 后缀」形态（申辩意 / 申辩意见 / 申辩权 / 申请书），
    词根本身由 NON_NAME_WORDS 精确匹配负责，不重复。
    """
    if not word or len(word) < 3:
        return False
    return any(word.startswith(r) and len(word) > len(r)
               for r in NON_NAME_PREFIX_ROOTS)


