def looks_like_name(word, strict=False):
    """单看一个词，像不像中国人名（不看上下文）。

    判据：2-4 字 / 首字（或前两字）是姓氏 / 不是排除表常用词 /
    名字部分不含代词 / 名字里没有机构或数字单位字。

    strict=True：低置信场景（孤立候选）用，额外排除「兼职虚词的姓氏」。
    「和」「与」「从」「于」这些字当连词远多于当姓，
    不加约束会把「和我说的一样」当成「和某」。
    """
    if not (2 <= len(word) <= 4):
        return False
    if word in NON_NAME_WORDS:
        return False
    if blocked_by_doc_root(word):     # 2026-11-05：公文词根的三字延伸词
        return False
    # 序数不是人名：「第」虽是极罕见姓，但在文书里几乎只作序数前缀。
    # 不挡的话「讯问笔录（第一次）」会被切成姓名「第一」→ 脱成「第某次」。
    if word[0] == "第":
        return False
    given = _given_part(word)
    if not given:
        return False
    if word in PRONOUNS or any(p in given for p in PRONOUNS) or given in PRONOUNS:
        return False
    if strict:
        sur, _g = split_surname(word)
        if sur in FUNCTION_SURNAMES:
            return False
    # 学历/文书用语前缀：中学、高中、初中、小学、大学、大专…
    # 「汉族，高中文化」会被切出「高中文」，必须挡住。
    if given[:1] in "中小大高初":
        if any(w in word for w in ("高中", "初中", "小学", "中学", "大学", "大专",
                                   "中专", "高中文", "本科", "硕士", "博士")):
            return False
    if len(given) <= 2 and any(
            ch in "局院所厅部委办站队科处室号条项款元角分年月日" for ch in given):
        return False
    # 机构/公司/店铺通名：这类词是组织不是人。
    # 「某某商贸有限公司」「某某超市」首字可能是姓氏，
    # 不挡的话会被化名成「武某达商贸有限公司」「关某合超市」，把企业名劈成两半。
    if any(w in word for w in ORG_LIKE_WORDS):
        return False
    # 地名前缀：3 字以上且以省市名打头的，基本是「地名 + 字号」的主体简称，
    # 不是人名。「武汉某信」曾被化名成「武某」，把公司写成了个人。
    if len(word) >= 3 and any(word.startswith(p) for p in PLACE_PREFIX):
        return False
    # 名字末尾不收这些字（2026-11-03 补）
    # 「供述某某某于当晚」会被切成「某某某于」——「于」是名字用字，
    # 但它在这里是介词。人名的末字极少是介词/助词，
    # 见到就把最后一个字剥掉，而不是整条丢掉（某某某本身是真名）。
    if len(word) >= 3 and word[-1] in "于在向从对与及并且是在有和跟同被把使让给":
        return False
    return True
