def is_compound_surname(word):
    """是否复姓开头（取前两字判断）。"""
    return len(word) >= 3 and word[:2] in _COMPOUND_SET


def split_surname(name):
    """拆出 (姓, 名)。复姓返回两字姓。"""
    if not name:
        return "", ""
    if len(name) >= 3 and name[:2] in _COMPOUND_SET:
        return name[:2], name[2:]
    return name[0], name[1:]


def _given_part(word):
    """取出名字部分（复姓去两字，其余去一字）。取不到返回空。"""
    if len(word) >= 3 and word[:2] in _COMPOUND_SET:
        return word[2:]
    if word and word[0] in SINGLE_SURNAMES:
        return word[1:]
    return ""


_NAME_GAP_CHARS = " \t\u00a0\u3000\u200b\u200c\u200d\ufeff"

# 紧跟在姓名后面、**不是名字一部分**的称谓/身份词。
# 2026-11-18 实测：「党支部书记、董事长杨某某同志在9楼会议室」被识别成「杨某某同」——
# 「同」恰好在 NAME_CHARS 里，于是「同志」的「同」被当成第三个名字字吃进去了。
_NAME_STOP_WORDS = (
    "同志", "先生", "女士", "小姐", "律师", "法官", "检察官", "书记", "主任",
    "经理", "董事长", "总经理", "局长", "院长", "校长", "厂长", "所长", "科长",
    "处长", "部长", "厅长", "队长", "站长", "会长", "社长", "主席", "委员",
    "代表", "教授", "医生", "老师", "会计", "总监", "主管", "顾问", "助理",
    "等人", "等", "系", "现", "时", "于", "在", "与", "和", "及", "为", "是",
)


def _is_title_start(text, k):
    """从 k 开始是不是某个称谓词的开头。

    取名字字时用它预判：「杨某某同志」取到第 3 个字「同」之前，
    发现 text[k:] 以「同志」开头，立刻停手 —— 名字是「杨某某」。
    不能等「同」取进去再回退：那时 end 停在「同」后面，
    找不到完整的「同志」，退无可退（上一版就是这么错的）。
    """
    for w in _NAME_STOP_WORDS:
        if text.startswith(w, k):
            return True
    return False


def match_name_at(text, i):
    """从 text 的第 i 个字符开始，尝试识别一个中文姓名。

    返回 (姓名, 结束位置) 或 None。

    做法：先认复姓（2 字），再认单姓（1 字），随后取 1-2 个**名字用字**。
    关键约束是名字字必须来自 NAME_CHARS：
      「的某某某通知我」里，若只按长度取 4 字会切出「某某某通」，
      「通」不在名字用字里，于是正确停在「某某某」。
    这条约束同时解决了「某某某在」被切成人名的问题（「在」不是名字字）。

    2026-11-18 两处补强（用户报「自动人名识别错了」）：
      1. 字间允许排版空白：「徐  磊」「张 绪」是 Word 断字，不是两个人；
      2. 取字前预判称谓词：「杨某某同志」停在「杨某某」，不能是「杨某某同」。
    """
    if not text or i >= len(text):
        return None

    def _given_from(j, limit=2):
        """取 j 之后最多 limit 个名字字，允许字间夹空白。返回 (名字, 结束位置)。"""
        got = ""
        while len(got) < limit:
            k = j
            # 跳过字间空白；空白超过 3 个就认为不是同一个人名（跨了分栏/换行）
            while k < len(text) and text[k] in _NAME_GAP_CHARS:
                k += 1
            if k > j + 3 or k >= len(text):
                break
            if _is_title_start(text, k):
                break
            if text[k] in NAME_CHARS:
                got += text[k]
                j = k + 1
            else:
                break
        return got, j

    # 复姓优先（取两字姓，名 1-2 字）
    if i + 2 < len(text) and text[i:i + 2] in _COMPOUND_SET:
        sur, j = text[i:i + 2], i + 2
        given, j = _given_from(j)
        if given:
            return text[i:j], j
        return None
    # 单姓
    if text[i] in SINGLE_SURNAMES:
        given, j = _given_from(i + 1)
        if given:
            return text[i:j], j
    return None


def scan_names_by_surname(text, strict=True):
    """全文扫描：凡是从姓氏字开始、后接名字用字的位置，都尝试取姓名。

    这是召回率最高的一路（不依赖栏目、不依赖上下文），
    精度靠 NAME_CHARS 约束 + NON_NAME_WORDS 排除表 + 前后字检查。
    返回 {姓名: 次数}
    """
    if not text:
        return {}
    hit = {}
    i, n = 0, len(text)
    # 允许在姓名前出现的字（虚词/标点）
    # 认代晓请才：这几个字「既是名字用字、又常作引出人名的动词」，
    # 只靠「前字不是名字用字」的结构性判据会被挡掉（典型：指认刘德华为嫌疑人）。
    PRE_OK = ("的由经被向对给和与跟同是在为把让使从于到去来及并"
              "认代晓请才"
              # 2026-11-03 刑事案卷补：这些字既算"名字用字"，又是笔录里
              # 引出人名的动词。不列进来，「你是否认识某某某」「供述某某某」
              # 「指认刘德华」整片漏 —— 而这正是笔录问名字的标准句式。
              "识述供指见说叫问讲提获捕抓送带遇碰听知得讯审查询控举报"
              "约雇派托访交代称到有未已曾又还就均即另据")
    # 会「引出人名」的动词/引出字：2 字名靠它放行，同时不给普通实词开门。
    LEAD_VERBS = (
        "述见识供指找说叫问讲提获捕抓送带遇碰听知得讯审查询控举报"
        "约雇派托访交代称到出来去上有无未已曾又还就才均即另据连同"
        "纠伙邀陪会同陪帮替代靠随替向"
    )
    # 角色词直接接人名：刑事案卷里最高频的写法，且**必须**命中。
    #
    # 2026-11-03 用户原话："ai 对于刑事案卷要着重启动名字这项屏蔽啊"
    # 实测漏得最狠的就是这一类：
    #   「被调查人王某某」——「人」是 NAME_CHARS 里的字，
    #     结构性判据认定「人王某某」是一个更长的词，整条姓名被挡掉；
    #   「讯问人张律师」「记录人某某某」「证人某某某」同样被挡。
    # 而这些恰恰是笔录里点名道姓的地方，漏一个就等于没脱敏。
    #
    # 做法：角色词（ROLE_WORDS 里的词）后面紧跟的人名，无条件认。
    # 安全性：ROLE_WORDS 是封闭的词表，"讯问人""被调查人"后面
    # 在语义上只可能跟人名或留空，不会跟普通实词。
    ROLE_LEAD = tuple(sorted(ROLE_WORDS, key=len, reverse=True)) if ROLE_WORDS else ()
    while i < n:
        got = match_name_at(text, i)
        if not got:
            i += 1
            continue
        name, end = got
        # 尾部修剪：match_name_at 按「姓+最多2个名字用字」定界，
        # 名词/介词挡不住。「供述某某某于当晚」切出「某某某于」，
        # 正确做法是把「于」剥掉留下真名，而不是把整条候选丢掉。
        # 只剥一个字的介词/助词，剥完仍需是合法人名。
        while len(name) >= 3 and name[-1] in "于在向从对与及并且是在有和跟同被把使让给的了着过":
            if looks_like_name(name[:-1]):
                name = name[:-1]
                end -= 1
                break
            name = name[:-1]
            end -= 1
        prev_ch = text[i - 1] if i > 0 else ""
        next_ch = text[end] if end < n else ""
        # 前面：句首/标点/空白/虚词都可以；不能是普通实词字（否则是长词中段）
        #
        # 为什么再加一档「前一个字不是名字用字」：
        # PRE_OK 是人工白名单，穷举不完。「你是否认识某某某？」的「识」、
        # 「看见某某某」的「见」、「供述某某某」的「述」都不在白名单里，
        # 结果叙述句里的姓名整片漏掉 —— 这正是用户反复反馈的
        # 「姓名必须隐去啊，全名还是留了好多」的残留根源。
        # 判据换成结构性的：只要前一个汉字**不是名字用字**，
        # 说明姓氏字在这里是另起一个词，不是某个更长的词的中段，
        # 可以安全收下。反过来「文章伟大」的「文」是名字用字，
        # 「章伟大」就会被挡住，不会出现硬从词里抠人名的情况。
        prev_ok = (i == 0) or (not ("\u4e00" <= prev_ch <= "\u9fa5")) \
            or (prev_ch in PRE_OK) or (prev_ch not in NAME_CHARS)
        # 角色词在前：无条件认（刑事案卷里「被调查人X」「讯问人X」是点名道姓处）
        after_role = False
        for _rw in ROLE_LEAD:
            if i >= len(_rw) and text[i - len(_rw):i] == _rw:
                after_role = True
                break
        if after_role:
            prev_ok = True
        # 不做「向后延长」：match_name_at 已按「姓 + 最多 2 个名字用字」定界，
        # 延长只会切出「某某某在」「某某某通」这类残词（实测过）。
        if prev_ok and looks_like_name(name, strict=strict):
            # 2 字候选与常用词同形极多，误伤代价高：只有被虚词引出
            # 或紧贴标点独立出现时才接受；3 字以上极少与常用词碰撞，正常收。
            if len(name) == 2:
                # 2 字候选与常用词同形极多（水平/终结/权利/和平…），
                # 实测过「前字不是名字用字就收」这条结构规则太松：
                # 建设「水平」、侦查「终结」、股东「权利」全被当成人名。
                # 所以 2 字名仍用白名单，但把白名单扩到「会引出人名的动词」——
                # 供述/看见/认识/指认/找到/听说/抓获/交代… 这些字后面跟人名
                # 是笔录里最常见的句式，不扩就会整片漏掉真名。
                boundary = (not ("\u4e00" <= (prev_ch or "，") <= "\u9fa5")) \
                    or (prev_ch in PRE_OK) or (prev_ch in LEAD_VERBS) or after_role
                if not boundary:
                    i = end if end > i else i + 1
                    continue
            hit[name] = hit.get(name, 0) + 1
        i = end if end > i else i + 1
    return hit
    """单看一个词，像不像中国人名（不看上下文）。

    判据：2-4 字 / 首字（或前两字）是姓氏 / 不是排除表里的常用词 /
    名字部分不含代词。

    strict=True：低置信场景（孤立候选）用，额外排除「兼职虚词的姓氏」。
    「和」「与」「从」「于」这些字当连词的时候远多于当姓的时候，
    不加约束会把「和我说的一样」当成「和某」。
    """
    if not (2 <= len(word) <= 4):
        return False
    if word in NON_NAME_WORDS:
        return False
    given = _given_part(word)
    if not given:
        return False
    # 名字里含代词 → 一定不是人名
    if any(p in given for p in PRONOUNS) or given in PRONOUNS:
        return False
    if word in PRONOUNS:
        return False
    # 孤立候选场景：虚词姓氏不认
    if strict:
        sur, _g = split_surname(word)
        if sur in FUNCTION_SURNAMES:
            return False
    # 名字部分不能含明显非人名字（机构/数字/单位）
    if any(ch in "局院所厅部委办站队科处室号条项款元角分年月日" for ch in given) \
            and len(given) <= 2:
        return False
    return True


