# ============ 六、学习库接入 ============
# 基础库是硬编码的「先天知识」，学习库是每次办案沉淀的「后天经验」。
# 使用时取并集——这样引擎会随着使用越来越懂，而不是永远死板一套。
#
# 注意：本地千问的模型权重不会自己变化，所谓「学习」就是把经验落成规则，
# 落成本文件读取的 learned.json，下次启动自动生效。
_LEARNED_CACHE = None


def load_learned(path=None):
    """读取学习库（learned.json），返回 dict。找不到返回空结构。"""
    global _LEARNED_CACHE
    if _LEARNED_CACHE is not None and path is None:
        return _LEARNED_CACHE
    import json as _json
    cands = []
    if path:
        cands.append(path)
    cands.append(os.path.join(HERE, "learned.json"))
    cands.append(os.path.join(
        os.path.expanduser("~"), "Library", "Application Support",
        "立丰脱敏", "记忆库", "learned.json"))
    data = {}
    for p in cands:
        try:
            with open(p, "r", encoding="utf-8") as f:
                data = _json.load(f)
            break
        except Exception:
            continue
    if path is None:
        _LEARNED_CACHE = data
    return data


def learned_items(bucket):
    """取学习库里某一类的键集合。"""
    d = load_learned()
    return set(d.get(bucket, {}) or {})


