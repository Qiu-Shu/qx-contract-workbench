# 绝对不要用 ~/Documents/立丰脱敏 这个名字：
# 那里有一个指向 /Applications/立丰脱敏.app 的符号链接（App 快捷方式），
# 往这个路径写文件等于往 App 安装包里写，用户既找不到、还会破坏 App 结构。
# 实测踩过：词表被塞进 App 包根目录，用户反馈「找不到词表」。
_BAD_PATHS = (
    os.path.expanduser("~/Documents/立丰脱敏"),
    "/Applications/立丰脱敏.app",
)


def _assert_dir_safe(path):
    """确保输出目录不是符号链接、也不在 App 包内。"""
    real = os.path.realpath(path)
    for bad in _BAD_PATHS:
        rb = os.path.realpath(bad)
        if real == rb or real.startswith(rb + os.sep):
            raise SystemExit(
                "拒绝写入 %s：该路径是 App 的符号链接或安装包内部，"
                "写进去用户找不到文件。请改用 ~/Documents/立丰脱敏词表" % path)
    if os.path.islink(path):
        raise SystemExit("拒绝写入 %s：这是符号链接，会被写到链接目标里" % path)


_assert_dir_safe(OUT_DIR)
os.makedirs(OUT_DIR, exist_ok=True)


def _surname_block():
    """姓氏库章节：单姓按每行 20 字排，复姓每行 10 个。"""
    singles = sorted(C.SINGLE_SURNAMES)
    lines = []
    for i in range(0, len(singles), 20):
        lines.append("  " + " ".join(singles[i:i + 20]))
    comp = list(C.COMPOUND_SURNAMES)
    comp_lines = []
    for i in range(0, len(comp), 10):
        comp_lines.append("  " + " ".join(comp[i:i + 10]))
    return lines, comp_lines


