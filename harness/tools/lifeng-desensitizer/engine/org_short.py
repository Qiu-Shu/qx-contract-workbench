# ============ 三、行政级别字（用于拼「市检察院」这类） ============
LEVEL_LABEL = {"省": "省", "市": "市", "区县": "区", "街道": "街道"}


def _level_label(name, level):
    """按**实际出现的层级字**出标签：县→县、区→区、旗→旗、县级市→市。

    2026-10-26 实测：「黎平县公安局」被简写成「区公安局」、「锦屏县看守所」被写成
    「区看守所」——县和区是两个不同的管辖层级，一律写成「区」，
    案卷里就分不清是县局办的还是区分局办的，属于「脱完读不懂」。
    """
    if not level:
        return ""
    for lv, marks in LEVEL_MARKS:
        if lv != level:
            continue
        best, best_p = "", -1
        for mk in marks:
            p = name.rfind(mk)
            if p > best_p:
                best_p, best = p, mk
        if best == "县级市":
            return "市"
        if best:
            return best
    return LEVEL_LABEL.get(level, "")

# 具体房间号（第3讯问室 / 第5监室）：保留，帮助理解文书，不指向具体人
_LOC_RX = re.compile(
    r"(第\s*[\d一二三四五六七八九十]+\s*"
    r"(?:讯问室|询问室|监室|监房|提讯室|会见室|审判庭|法庭|询问处))")


def _nearest_level(name):
    """取名称里**最靠近末尾**的层级标记，但要排除专名里的假层级字。

    为什么不能简单 rfind：「湖北京山县公安局新市派出所」里
    「新市」的「市」比「京山县」的「县」更靠后，会被误判成市级。
    真实层级字总是紧跟在行政区专名后、且后面接机构或边界，
    而「新市镇」这类是地名的一部分。
    这里对「市」加一条约束：前面不能是「新/旧/东/西/南/北/沙/…」这类
    常见地名用字，且整体要像「XX市」。
    """
    best_pos, best_lv = -1, None
    for lv, marks in LEVEL_MARKS:
        for mk in marks:
            start = 0
            while True:
                p = name.find(mk, start)
                if p < 0:
                    break
                start = p + 1
                # 「市」前若是方位/常见地名首字，多半是「新市镇」这类专名，不算层级
                if mk == "市" and p > 0 and name[p - 1] in "新旧东西南北中上下大小沙哈":
                    continue
                if p > best_pos:
                    best_pos, best_lv = p, lv
    return best_lv


def _find_all_types(name):
    """找出名称里所有机构类型，返回 [(简写, 固定层级, 关键词, 位置)]，按位置排序。

    关键：**重叠匹配取长的**。
    「中级人民法院」同时能匹配「中级人民法院」和「人民法院」，
    取短的就丢掉了「中级」这个决定性信息；「刑侦大队」同理会被「大队」覆盖。
    """
    found = []
    for kw, short, fixed in ORG_TYPES:
        pos = name.find(kw)
        while pos >= 0:
            found.append((short, fixed, kw, pos))
            pos = name.find(kw, pos + 1)
    if not found:
        return []
    # 先按关键词长度降序，长的优先占位；短的重叠项直接丢弃
    found.sort(key=lambda x: -len(x[2]))
    kept = []
    for item in found:
        s, e = item[3], item[3] + len(item[2])
        overlapped = False
        for k in kept:
            ks, ke = k[3], k[3] + len(k[2])
            if s < ke and e > ks:          # 区间重叠
                overlapped = True
                break
        if not overlapped:
            kept.append(item)
    return sorted(kept, key=lambda x: x[3])


# 内设机构：必须挂在前面某个主机构之下，自己不能当主机构
_SUB_UNITS = frozenset({
    "刑侦大队", "刑侦支队", "经侦大队", "经侦支队", "禁毒大队", "禁毒支队",
    "治安大队", "交警大队", "交警支队", "特警大队", "国保大队", "网安大队",
    "法制大队", "刑警大队", "刑警支队", "大队", "支队", "中队",
    "检察部", "检察室", "审判庭", "刑庭", "民庭", "执行局",
})

# 基层机构：本身即街道/乡镇级，不再叠加地名层级
# 「公安分局」也放进来：它本身就是区县级机构，且「洪山分局」这类
# 原名里常不带「区」字，猜层级必错（会算成市级）。直接输出「公安分局」最准。
_GRASSROOTS = frozenset({"派出所", "警务室", "司法所", "公安分局"})


def _pick_org_type(name):
    """选定主机构。返回 (主机构四元组, 内设机构四元组或 None)。

    规则：机构名结构是「地名 + 主机构 + 内设机构」。
    若最后一个匹配是内设机构（刑侦大队/检察部…），它属于**前面最近的机构**，
    自身不能当主机构——否则「武汉市公安局洪山分局刑侦大队」会只剩「市刑侦大队」，
    把公安机关整个丢掉。
    """
    items = _find_all_types(name)
    if not items:
        return None, None
    last = items[-1]
    if last[0] in _SUB_UNITS and len(items) >= 2:
        # 往前找最近的非内设机构作为主机构
        for it in reversed(items[:-1]):
            if it[0] not in _SUB_UNITS:
                return it, last
        return items[0], last
    return last, None


def summarize_org(name):
    """把「地名 + 机构全称」压成「级别 + 机构类型（+ 内设 + 房间）」。

    武汉市公安局洪山分局刑侦大队 → 市公安分局刑侦大队
    湖北省武汉市洪山区第一看守所第3讯问室 → 区看守所第3讯问室
    武汉市洪山区人民检察院第一检察部 → 区人民检察院第一检察部
    湖北省武汉市中级人民法院 → 市中级人民法院
    关山派出所 → 派出所
    """
    if not name:
        return ""
    s = name.strip().replace("中华人民共和国", "")

    main, sub = _pick_org_type(s)
    if not main:
        return ""
    short, fixed, kw, pos = main

    # 层级：机构自带（高级法院=省、中级法院=市）优先；否则取机构名前最靠近的层级
    # 基层机构（派出所/司法所/警务室）本身就是街道级，不再猜地名层级，
    # 否则「湖北京山县公安局新市派出所」会被算成「市派出所」。
    if fixed:
        level = fixed
    elif short in _GRASSROOTS:
        level = None
    else:
        level = _nearest_level(s[:pos]) or None
    lv_label = _level_label(s[:pos], level)

    out = (lv_label if lv_label and not short.startswith(lv_label) else "") + short

    # 内设机构（检察部/刑侦大队…）：只要不是主机构的完全同义重复就拼上。
    # 不能用 _overlaps 判：它会把「第一检察部」和「人民检察院」因为共有「检察」二字判成重复，
    # 结果丢掉「检察部」，读者就不知道是哪个部门办的案。
    if sub:
        # 主机构简写已包含内设名（"公安分局"含"分局"）才跳过
        if sub[0] not in short and short not in sub[0]:
            out += sub[0]

    # 具体房间号（第3讯问室）保留：帮助理解文书，且不指向具体人
    m = _LOC_RX.search(s)
    if m:
        loc = re.sub(r"\s+", "", m.group(1))
        if loc not in out:
            out += loc

    return out


def _overlaps(a, b):
    """两个简写名是否高度重叠（避免「公安局公安分局」「司法局司法所」）。"""
    if not a or not b:
        return False
    if a in b or b in a:
        return True
    # 共同子串达到较短者一半以上即视为重复
    short, long_ = (a, b) if len(a) <= len(b) else (b, a)
    for i in range(len(short)):
        for j in range(i + 2, len(short) + 1):
            if short[i:j] in long_ and (j - i) * 2 >= len(short):
                return True
    return False


