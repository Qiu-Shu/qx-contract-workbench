def _learned_org_types():
    """把学习库里的机构类型并进来。

    基础表是「先天知识」（公安/检察/法院/司法/国安/羁押/鉴定），
    学到的类型（如城管局、综合执法局、纪委监委）是「后天经验」——
    碰到一次生僻机构，确认后就永久生效，不用每次重新猜。
    """
    try:
        import chinese_names as C
        d = C.load_learned()
        got = []
        for word, meta in (d.get("org_types") or {}).items():
            short = (meta or {}).get("简写") or word
            if word and len(word) >= 2:
                got.append((word, short, None))
        return tuple(got)
    except Exception:
        return ()


