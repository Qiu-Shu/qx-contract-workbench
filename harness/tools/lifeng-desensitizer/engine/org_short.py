#        北京市朝阳区建国路88号              → 北京市地名
#        洪山区珞南街道民院路128号           → 地名（没有省市可留）
#   ② 涂抹范围：只涂「区级以下」那一段，省市不涂。
#        图片上整条地址涂黑会把整行糊掉，影响阅读（用户明确反馈）。

# 省级前缀（含自治区、直辖市、特别行政区）
