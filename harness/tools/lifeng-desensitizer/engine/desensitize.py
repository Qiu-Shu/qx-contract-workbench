        # 可公司全称只写在抬头段，正文段里只有字号（「远景科技园三期土建工程」）。
        # 逐段调用 redact_text 时，正文段拿到的 party_names 恒为空 → 字号一个都脱不掉。
        # 所以必须在全文级预扫：先把所有公司全称抹成占位，剩下的字号出现就是回指。
        names = list(co2role.keys()) + [nm for _a, _b, nm in _company_spans(full_text)]
        masked = full_text
