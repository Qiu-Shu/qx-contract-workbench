def _is_org_name_at(text, end):
    """name 在 text[:end] 结束，判断它后面紧接的是不是机构组织形式词。

    ⚡ 2026-11-07 修「公司名被脱成 X 某」：
        `被告：张记餐饮有限公司` —— person_spans 在「被告：」后面
        `match_name_at` 只吃到「张记餐」三个字（「饮」不在姓名用字表），
        角色词托底（strong=True）又让它绕过常用词检查，于是
        「张记餐」被当成一个人名，脱成「张某」，成品变成
        「被告：张某饮有限公司」——公司名被从中间劈开。
        判据很明确：**人名后面不会紧跟「有限公司」「事务所」这种东西**。

    ⚠ 不能只判 `tail.startswith(后缀)`：截断点往往落在字号中间，
        `张记餐|饮有限公司` 的 tail 是「饮有限公司」，不以「有限」开头。
       正确判据是「tail 里前几个字之内出现了机构后缀」，因为字号残余
       最多两三个字，再往后必然是组织形式。
    """
    if not text or end <= 0:
        return False
    tail = text[end:end + 20]
    if not tail:
        return False
    if tail.startswith(_ORG_TAIL_WORDS):
        return True
    # 截断点落在字号中间：name 尾部还有若干字号字，之后紧跟组织形式。
    # 例：「张记餐」+「饮有限公司」、「李宁」+「体育用品有限公司」、
    #     「王家」+「大院餐饮有限公司」、「安顺建」+「材有限公司」。
    # 上限取 6 而不是 3 —— 字号里「体育用品」「大院餐饮」这种四字组合很常见，
    # 卡 3 会漏掉一半。再长就说明不是同一个机构名了（人名不会连着六七字
    # 都凑不出标点），所以 6 是够用的上界。
    for _skip in range(1, 7):
        if tail[_skip:].startswith(_ORG_TAIL_WORDS):
            return True
    return False


def _match_name_strong(text, i):
    """角色词托底时的宽松匹配：姓氏 + 1~2 个汉字（不要求字表命中）。

    为什么需要：chinese_names.NAME_CHARS 是精度闸门，但字表不可能穷举。
    实测「辩护人陈立国」——「立」不在名字用字表里，match_name_at 直接返回 None，
    整个真名漏掉。有角色词托底（辩护人/被告人/证人…）时，
    姓氏本身就是最强的信号，字表只用来兜精度，不该用来一票否决。
    仍然守住的底线：程序词、地名、机构通名、标点、虚词一律不认。
    """
    if not text or i >= len(text):
        return None
    try:
        import chinese_names as C
    except Exception:
        return None
    if text[i:i + 2] in getattr(C, "_COMPOUND_SET", ()):
        sur, j = text[i:i + 2], i + 2
    elif text[i] in C.SINGLE_SURNAMES:
        sur, j = text[i], i + 1
    else:
        return None
    STOP = "的了在是和与等将把被向对为及并或者地得着过也就都还又很" \
           "局院所厅部委办公司年月日号第条款项元"
    gap = getattr(C, "_NAME_GAP_CHARS", " \t\u00a0\u3000")
    title_start = getattr(C, "_is_title_start", None)
    given = ""
    while j < len(text) and len(given) < 2:
        # 2026-11-18：字间允许排版空白（「徐  磊」），否则列席名单整串断掉
        k = j
        while k < len(text) and text[k] in gap:
            k += 1
        if k > j + 3 or k >= len(text):
            break
        if title_start and title_start(text, k):
            break            # 「杨某某同志」必须停在「杨某某」
        ch = text[k]
        if not ("\u4e00" <= ch <= "\u9fa5") or ch in STOP:
            break
        given += ch
        j = k + 1
    if not given:
        return None
    # 2026-11-18：返回**原文片段**而不是 sur+given。
    # 原文「张  绪」被 Word 断字，拼成「张某某」就再也回不到原文里 ——
    # 后面 text.replace("张某某", …) 匹配不到「张  绪」，人名原样留着。
    # 用 text[i:j] 把中间的空格一起带出来，替换时整段端掉。
    return text[i:j], j


def person_spans(text):
    """返回 ([(起, 止, 姓名)], 姓名集合)：角色词后、顿号连排里的人名。"""
    if not text:
        return [], set()
    try:
        import chinese_names as C
    except Exception:
        return [], set()
    roles = sorted({r for r in C.ROLE_WORDS if len(r) >= 2} | set(_EXTRA_ROLES),
                   key=len, reverse=True)
    if not roles:
        return [], set()
    rx = re.compile(r"(?:%s)\s*[：:]?\s*" % "|".join(map(re.escape, roles)))
    spans = []
    for m in rx.finditer(text):
        i = m.end()
        _weak = any(m.group(0).startswith(w) for w in _WEAK_ROLE)
        _got_any = 0                # 这条角色词后已经认出几个人名
        for _ in range(16):         # 一条角色词后最多连排 16 个人名（名单常见 9~12 人）
            got = C.match_name_at(text, i)
            # 2026-11-18：字表没收录的名字会被 match_name_at **截短**
            # （「伍某某」→「伍新」，因为「桐」不在 NAME_CHARS）。
            # 截短不只是少脱一个字：end 停在「桐」上，顿号连排立刻断掉，
            # 后面「张某某、望某某」整串跟着全漏。角色词后放宽兜底，取更长的那个。
            _strong = _match_name_strong(text, i)
            if _strong and (not got or len(_strong[0]) > len(got[0])):
                got = _strong
            if not got:
                # 2026-11-18：生僻姓（「望某某」的「望」不在常见姓表）认不出时，
                # 原来直接 break —— 一个生僻姓就把后面「陈 树、江 航、李  莉、
                # 吴某某」整串名单全废。已经认出过人名说明这是名单，
                # 跳过**当前这一项**继续试（注意只能跳一项：跳到下一个顿号会
                # 把「望某某 陈 树」里的「陈 树」一起跳掉，实测漏脱）。
                if _got_any:
                    _nx = re.search(r"[、，,\s]", text[i + 1:i + 16])
                    if _nx:
                        i += 1 + _nx.end()
                        continue
                break
            name, end = got
            if not _ok_person(name, strong=not _weak):
                # 右边界回退：「江山与原告周逸翰」会先捞到「江山与」，
                # 末字是连词就退一格再判，「与」必须还给句子。
                # 「到」也在这张表里：「被告人高明到案后」会先捞到「高明到」，
                # 不退一格就把真名「高明」一起丢了（2026-10-27 闸门当场抓到）。
                if len(name) >= 3 and name[-1] in "与及或和等将对向为在是并的着过到":
                    name, end = name[:-1], end - 1
                if not _ok_person(name, strong=not _weak):
                    if _got_any:
                        _nx = re.search(r"[、，,\s]", text[i + 1:i + 16])
                        if _nx:
                            i += 1 + _nx.end()
                            continue
                    break
            spans.append((i, end, name))
            _got_any += 1
            i = end
            sep = _NAME_CTX_TAIL.match(text[i:])
            if not sep:
                break
            i += sep.end()
    # 姓名栏：曾用名/别名/化名/又名 后面的内容同样是姓名，必须一起脱。
    # 2026-10-27 实测：「被告人付丽华，曾用名阿丽华」原来把「曾用名」
    # 当成人名脱成「曾某」，真别名「阿丽华」反倒原样留着——两头都错。
    for m in re.finditer(r"(?:%s)\s*[：:，,]?\s*"
                         % "|".join(sorted(set(_NAME_FIELD_WORDS), key=len, reverse=True)),
                         text):
        i = m.end()
        got = C.match_name_at(text, i) or _match_name_strong(text, i)
        if not got:
            # 别名不一定是「姓氏+名」（「阿丽华」的「阿」不在姓氏表），
            # 但「曾用名：」本身已是足够的结构证据，按 2-4 字直接取。
            mm = re.match(r"[\u4e00-\u9fa5]{2,4}", text[i:])
            if mm and mm.group(0) not in ("男性", "女性", "汉族", "无业", "群众"):
                spans.append((i, i + len(mm.group(0)), mm.group(0)))
            continue
        name, end = got
        if _ok_person(name, strong=True):
            spans.append((i, end, name))
    # 叙述句事实认定引导词后的真名（2026-10-28，连挂三日的 P0 收口）
    # 「经依法鉴定，杨通远盗窃」「经审理查明，杨通远于」「经查，杨通远曾因」——
    # 前面没有任何角色词托底，全文扫描又会把「经过六」「应诉通」「金人民」当人名。
    # 完整文书里这类名字其实已被「同篇传播」兜住（抬头被告人杨通远→正文同名替换），
    # 真正漏的是单句片段。这里只认「经X查明/鉴定 + 逗号冒号 + 严格字表姓名」这一种
    # 窄结构，且名字后不能紧跟数字（排除「经过六十日」），不做无锚点的全文瞎猜。
    for m in re.finditer(r"(?:%s)\s*[：:，,]\s*"
                         % "|".join(sorted(("经依法审查查明", "经依法鉴定",
                                           "经审理查明", "经依法查明",
                                           "经查明", "经查"), key=len, reverse=True)),
                         text):
        i = m.end()
        got = C.match_name_at(text, i)   # 严格字表：只收字表能确认的真名
        if not got:
            continue
        name, end = got
        nxt = text[end] if end < len(text) else ""
        if nxt.isdigit():
            continue
        if _ok_person(name, strong=False):
            spans.append((i, end, name))
    # 独立成行的「姓名：」（2026-10-27 千问复核发现）
    # 民事公告、送达公告的受送达人一律单独一行写明：「王守卫：」然后接正文。
    # 这类没有任何角色词托底，「经吴可彬介绍」那种叙述句也漏，本规则先收最硬的一种：
    # 行首 2~4 汉字 + 冒号 + 后面紧跟换行/文末。宁可只收这一种，也不做全文瞎猜。
    for m in re.finditer(r"(?:^|\n)[ 　\t]*([\u4e00-\u9fa5]{2,4})[ 　\t]*[：:][ 　\t]*(?=\n|$)",
                         text):
        name = m.group(1)
        # 栏位名不是人名：「日期：」「电子邮箱：」「甲方：」同样独占一行、
        # 同样冒号收尾，靠结构区分不了，只能靠栏位词表。
        if name in _FORM_FIELDS or any(name == w or name.startswith(w) for w in _FORM_FIELDS):
            continue
        if not _ok_person(name, strong=True):
            continue
        i = m.start(1)
        spans.append((i, i + len(name), name))
    if not spans:
        return [], set()
    # ⚡ 2026-11-07 统一出口过滤：名字右边紧跟机构后缀的，是公司字号不是人名。
    #
    # 四个入口（角色词后 / 曾用名栏 / 经查明 / 独立成行「姓名：」）都会捞出
    # 「张记餐」这种半截字号 —— 因为 `match_name_at` 只认姓名用字表，
    # 「饮」不在表里就停在「餐」，而角色词托底（strong=True）又绕过了常用词检查。
    # 放在出口统一过滤，比在四个入口各改一遍更不容易漏。
    #
    # 实测（修前）：`被告：张记餐饮有限公司` → `被告：张某饮有限公司`
    #              `保证人：安顺建材有限公司` → `保证人：安某建材有限公司`
    # 前者已被企业名规则完整识别过（`_company_spans` 给的是 0..8 整条），
    # 只是人名抢在前面先动了手 —— 所以这一步必须在 span 产出时就拦掉。
    _filtered = []
    for _a, _b, _nm in spans:
        if _is_org_name_at(text, _b):
            continue
        _filtered.append((_a, _b, _nm))
    spans = _filtered
    if not spans:
        return [], set()
    # 同一位置留最长（「王某某」不要被拆成「王某」+残字）
    spans.sort(key=lambda x: (x[0], -(x[1] - x[0])))
    out, last_end = [], -1
    for a, b, nm in spans:
        if a >= last_end:
            out.append((a, b, nm))
            last_end = b
    return out, {nm for _a, _b, nm in out}


# ============ 词表容错匹配（2026-11-11 用户要求）============
# 用户原话：「要是我给你脱敏词以后，但是原文里面脱敏词中间出现了空格
# 或者特殊符号，你没识别到，你看看有没有什么方法可以让你识别到的」
#
# 这些分隔符不是人打的，是**排版和提取过程**塞进去的：
#   · PDF / OCR 提取逐字断字：「武 汉 鑫 达 建 筑 工 程 有 限 公 司」
#   · 表格单元格折行：「某某建筑\n工程有限公司」
#   · 排版用的间隔号 / 连字符：「某某公司·建筑工程有限公司」
#   · 全角空格、不间断空格、零宽字符
# 精确 `text.replace()` 对上面每一种都全盲 —— 实测九种变体只有「正常」那一种命中，
# 其余八种词表里的公司名原样留在成品里，还带着企业名规则简写出来的「公司」尾巴，
# 看着像脱过了，其实主体一眼就能认出来。
#
# 做法：把词条拆成**实义字符**，字与字之间允许夹 0~3 个排版分隔符。
#
# ⚠ 绝不允许夹中文标点（，。；：！？、（）《》【】「」）。那是句子边界，
#   跨过去就等于把两句话连成一串，脱出来的东西读都读不懂。
#   中点「·」和连字符是例外 —— 音译名、公司名里本来就常用。
_TERM_GAP_SET = set(
    " \t\r\n\u00a0\u3000\u200b\u200c\u200d\u2060\ufeff"   # 空白与零宽
    "·•・"                                                # 中点
    "-–—‐‑−"                                              # 各种连字符
    "_.．/／\\|"                                           # 下划线/点/斜杠
)
_TERM_GAP_RX = (r"[\s\u00a0\u3000\u200b-\u200d\u2060\ufeff"
                r"·•・\-–—‐‑−_.．/／\\|]{0,3}")
# 2 字词专用：**不允许换行**，且间隔最多 2 个。
# 为什么不给 2 字词用上面那条（含 \s 里的 \n）：
#   「三峡」这种两字词一旦允许跨行，上一行末尾的「三」和下一行开头的「峡」
#   会被连起来 —— 那多半是两行不相干的内容（比如「第三」「峡口」）。
#   同一行里的空格、间隔号还要认，所以保留空格类，只把换行摘掉。
_TERM_GAP_RX_2 = (r"[ \t\u00a0\u3000\u200b-\u200d\u2060\ufeff"
                  r"·•・\-–—‐‑−_.．/／\\|]{0,2}")
# ⚡ 2026-11-11 晚：门槛从 3 降到 2。
# 用户当晚的词表 170 条里 **73 条是 2 字词**（三峡、武汉、湖北、某某某……），
# 占 43%；门槛卡在 3 等于把这四成词条全排除在容错之外，
# 原文写成「三 峡」「武 汉」就一条都认不出来 —— 用户原话「还是有好多」。
# 2 字词的误伤面其实很小：中间只允许夹**排版分隔符**，不允许汉字，
# 所以「原告李四 被告王五」不会被连成一个人（中间没有词条字符）。
_MIN_FUZZY_LEN = 2


def _term_core(term):
    """词条的实义字符序列 —— 剥掉排版分隔符后的「干词」。

    `138 1234 5678` → `13812345678`，这样原文写成 `138-1234-5678`
    或 `13812345678` 都能认出来。
    """
    return "".join(c for c in (term or "") if c not in _TERM_GAP_SET)


def _term_fuzzy_spans(text, term):
    """在 text 里找 term 的所有出现位置，允许字间夹排版分隔符。

    返回 [(start, end)]，end **包含中间的分隔符** —— 替换时必须整段端掉，
    只换实义字会留下「武 汉 」这种半截残渣，比不脱更难看。
    """
    core = _term_core(term)
    if not text or len(core) < _MIN_FUZZY_LEN:
        return []
    # 2 字词用「不跨行」的间隔规则，3 字以上才允许中间夹换行
    gap = _TERM_GAP_RX if len(core) >= 3 else _TERM_GAP_RX_2
    pat = gap.join(re.escape(c) for c in core)
    try:
        rx = re.compile(pat)
    except Exception:
        return []
    out = []
    for m in rx.finditer(text):
        # 跨度保险：中间要是夹了一大片空白（分栏、分页），宁可不认，
        # 也不能把两段不相干的内容一起端掉。正常逐字断字最多 len*2 左右。
        if m.end() - m.start() > len(core) * 4 + 8:
            continue
        out.append((m.start(), m.end()))
    return out


def load_terms(path, probe="", mode="criminal", trusted=False):
    """返回 [(原词, 替换词或 None)]，长词优先。

    trusted=True 表示这份词表是**人手工确认过的**（用户自己导入的「敏感词表.txt」），
    不是模型识敏生成的。区别在于下面「民事正文人名不化名」那条闸门：
    模型识敏会把「安装/双方/成本」误标成人名，所以要拦；
    但用户手写「李丽=李某」就是明确要换，再拦就成了「导了词表却不生效」。

    加载时做三道体检（见上面注释）：通名裸词、职务裸词、民事正文人名直接丢弃，
    留给结构化正则和人名规则处理，避免「拆了机构名、只脱职务」「把安装脱成安某」这类自伤。
    """
    rules = []
    if not path or not os.path.exists(path):
        return rules
    # 2026-10-28：词条闸门（与 gen_terms 共用 term_guard，单一口径）
    # 常用词即便被写进词表也不替换——历史词表里的 `安装=安某` 就是这么毁合同的。
    try:
        from term_guard import is_legal_common as _is_common, near_sign_context as _near_sign
    except Exception:
        def _is_common(_t):
            return False

        def _near_sign(_t, _x, span=16):
            return True
    civil = (mode == "civil")
    person_rx = re.compile(r'^[\u4e00-\u9fa5]{1,2}某\d*$')
    skipped = []
    skipped_people = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith("#"):
                continue
            if "=" in s:
                k, v = s.split("=", 1)
                k, v = k.strip(), v.strip()
                if _is_common(k):
                    skipped.append(k)
                    continue
                # 民事合同：正文人名不化名（用户 2026-10-28 要求）。
                # 词表里凡代号是「姓+某」的即为人名条目，除签章位外一律不替换——
                # 实测千问把「安装/烘干线/双方/成本/最终」全标成人名，脱完合同读不懂。
                # 2026-11-06：trusted（用户手工词表）不适用这条 —— 见 load_terms 注释。
                if civil and not trusted and person_rx.match(v or "") and not _near_sign(k, probe):
                    skipped_people.append(k)
                    continue
                # 只写原词不写替换词（`公安局=`）→ 传 None，
                # 由 _placeholder 按原文自动生成可读占位符。
                # 若传空字符串，替换后原文会被直接删掉，句子就断了。
                if not v and k in _BARE_ORG_WORDS:
                    skipped.append(k)
                    continue
                if not v and k in _POST_WORDS:
                    skipped.append(k)
                    continue
                rules.append((k, v if v else None))
            else:
                if s in _BARE_ORG_WORDS or s in _POST_WORDS:
                    skipped.append(s)
                    continue
                rules.append((s, None))
    rules.sort(key=lambda x: -len(x[0]))  # 长词优先，避免短词先替换破坏长词
    if skipped:
        sys.stderr.write(
            "词表体检：跳过 %d 条裸通名/职务词（交给结构规则处理）：%s\n"
            % (len(skipped), "、".join(sorted(set(skipped))[:12])))
    if skipped_people:
        sys.stderr.write(
            "词表体检：民事合同正文人名不化名，跳过 %d 条（保留签章位人名，如法定代表人/联系人）：%s\n"
            % (len(skipped_people), "、".join(sorted(set(skipped_people))[:12])))
    return rules


