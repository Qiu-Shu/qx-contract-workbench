    @classmethod
    def _is_law_url(cls, url):
        """该网址是否为法律/政府来源（保留），而非商业站点（脱敏）。"""
        u = (url or "").lower()
        return any(h in u for h in cls._LAW_URL_HOSTS)

    def _protect_fixed(self, text):
        """把 URL、国家级/省级司法机关换成哨兵，返回 (新文本, [(哨兵, 原文)])。"""
        spans = []
        # 网址保护是给**公文来源行**设计的：裁判文书网链接里带案号与对象名，
        # 被号码规则咬一口就变成「/ws532626/[银行卡号].html」，整行来源报废。
        #
        # ⚡ 2026-10-28 分模式（用户："联系方式也脱个敏"）：
        #    合同里的「官网：www.xxx.com」「公司网址：https://xxx」是**可反查主体的
        #    联系方式**，跟座机、邮箱同级，不能当来源引用放过。
        #    所以民事模式只保留法律/政府来源域名，其余网址交给 [网址] 规则脱掉；
        #    刑事模式维持原样（卷宗来源链接必须能回溯）。
        for m in re.finditer(_URL_RX, text):
            if self.mode == "civil" and not self._is_law_url(m.group()):
                continue          # 商业网址不保护 → 交给后面的 [网址] 规则
            spans.append((m.start(), m.end()))
        for m in re.finditer(r"(?<![A-Za-z0-9.\-])www\.[A-Za-z0-9.\-]+\.[A-Za-z]{2,}", text):
            if self.mode == "civil" and not self._is_law_url(m.group()):
                continue
            spans.append((m.start(), m.end()))
        # 2026-10-28 用户要求：金额一律不脱敏，「元」前面的数字原样保留。
        # 实测历史脏数据里出现过「（￥[编号]元）」——编号规则把金额吃了，这里提前保护。
        for rx in (re.compile(r'[￥¥]\s?\d[\d,，]*(?:\.\d+)?'),          # ￥8157500.00
                   re.compile(r'\d[\d,，]*(?:\.\d+)?\s*(?:亿元|万元|元)'),  # 8180000元 / 815.75万元
                   re.compile(r'[零壹贰叁肆伍陆柒捌玖拾佰仟万亿]{2,}元整?')):  # 捌佰壹拾伍万柒仟伍佰元整
            for m in rx.finditer(text):
                spans.append((m.start(), m.end()))
        for ph in self._KEEP_PHRASES:
            for m in re.finditer(re.escape(ph), text):
                spans.append((m.start(), m.end()))
        for rx in self._KEEP_RX:
            for m in rx.finditer(text):
                spans.append((m.start(), m.end()))
        if not spans:
            return text, []
        # 长串优先、去重叠：「最高人民法院」不能只保护住里面的「最高法」
        spans.sort(key=lambda x: (x[0], -(x[1] - x[0])))
        merged, last_end = [], -1
        for a, b in spans:
            if a >= last_end:
                merged.append((a, b))
                last_end = b
        out, last, toks = [], 0, []
        for a, b in merged:
            out.append(text[last:a])
            tok = "%sK%d%s" % (self._G0, len(toks), self._G1)
            toks.append((tok, text[a:b]))
            out.append(tok)
            last = b
        out.append(text[last:])
        return "".join(out), toks

