# 学习到的编号锚点 → 动态生成正则
# ============================================================================
# 用户要求「警号、车牌、律师证、各种文书编号都得脱敏，继续展开、类比学习」。
# 上面硬编码了 30 多条常见锚点；但编号种类无穷（每个机关都有自己的表号），
# 靠硬编码永远补不完。所以让引擎自己学：
#   每办完一个案子，从映射表里学到新的「XX号」锚点词 →
#   下次遇到「新锚点 + 号码」自动识别，不用改代码。
def _learned_anchor_rules():
    """从学习库读取学到的编号锚点，生成补充正则。"""
    rules = []
    try:
        import chinese_names as _C
        d = _C.load_learned()
        anchors = list((d.get("number_anchors") or {}).keys())
    except Exception:
        return rules
    known = {cat for cat, _rx in REGEX_RULES}
    for a in anchors:
        a = (a or "").strip()
        if len(a) < 3 or a in known:
            continue
        try:
            rx = re.compile(
                r"(?:%s)\s*[：:为]?\s*([0-9A-Za-z\u4e00-\u9fa5\-〔〕\[\]（）()]{3,40})"
                % re.escape(a))
        except Exception:
            continue
        rules.append((a, rx))
    return rules


# 追加到正则表末尾：学到的锚点优先级最低，不会抢已硬编码的规则
for _cat, _rx in _learned_anchor_rules():
    if _cat not in {c for c, _ in REGEX_RULES}:
        REGEX_RULES.append((_cat, _rx))


