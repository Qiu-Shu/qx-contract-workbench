def _looks_like_id(value):
    """18 位串是否真像身份证：第 7–14 位必须是合法的 YYYYMMDD。

    ⚡ 2026-10-28 新增。起因：施工许可证号「000000000000000000」也是 18 位纯数字，
    原先只按长度判断，被 `_id_placeholder` 标成「[湖北·2026年·身份证]」——
    占位符写错比不脱更误导读者，还会盖掉 [施工许可证号] 的正确结果。

    判据：月份 01–12、日期 01–31。不校验闰年与月份天数——
    这里只做「排除明显不是日期」的粗筛，精度够用即可。
    """
    v = (value or "").strip()
    if len(v) != 18 or not v[:17].isdigit():
        return False
    mm, dd = v[10:12], v[12:14]
    if not (mm.isdigit() and dd.isdigit()):
        return False
    return 1 <= int(mm) <= 12 and 1 <= int(dd) <= 31


def _id_placeholder(value):
    """身份证号：保留省份 + 出生年份，其余打码。

    用户要求「留前面省份开头，不然不知道脱敏是啥信息」。
    只留省份还不够直观，顺手保留出生年份——年份本身不是识别信息，
    但能让人一眼看出「这是个 1983 年出生的湖北人」，而不是一串 [编号]。
    """
    v = (value or "").strip()
    if len(v) < 6:
        return None
    prov = _ID_PREFIX.get(v[:2], v[:2])
    year = v[6:10] if len(v) >= 10 and v[6:10].isdigit() else ""
    return "[%s·%s年·身份证]" % (prov, year) if year else "[%s·身份证]" % prov


def _uscc_placeholder(value):
    """统一社会信用代码：保留登记部门 + 行政区划前 2 位，其余打码。

    用户要求「公司代码同理」。第 1 位是登记管理部门（9=工商、1=编制…），
    第 3-4 位是行政区划省级码，保留这两段就能看出是哪类主体、哪个省的。
    """
    v = (value or "").strip()
    if len(v) < 6:
        return None
    dept = _USCC_DEPT.get(v[:1].upper(), v[:1])
    prov = _ID_PREFIX.get(v[2:4], v[2:4])
    return "[%s·%s·统一代码]" % (prov, dept) if prov else "[%s·统一代码]" % dept


