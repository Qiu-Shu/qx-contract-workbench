_FADA_ROLES = ("法定代表人姓名", "法定代表人", "法人代表", "法定代理人",
               "执行事务合伙人", "负责人", "经营者",
               # 2026-10-28 补：合同签署页常见「法定代表人或授权代表：X」
               # 「委托代理人：X」「经办人：X」——都是签章位实名，按记忆铁律必脱
               "授权代表", "委托代理人", "签约代表", "经办人", "联系人")

_FADA_PAT = re.compile(
    r"(?P<role>" + "|".join(_FADA_ROLES) + r")"
    r"\s*(?:[（(][^）)]{0,10}[）)])?"
    r"\s*[：:，,]?\s*"
    r"(?P<name>[\u4e00-\u9fa5]{2,4})"
    r"(?=[\s，,。；;、）)\]】/｜|]|$)"
)

# 这些不是人名，即使 looks_like_name 误判也要挡掉（实测「须签字」会被判为人名）
_FADA_BLACKLIST = {"签字", "盖章", "日期", "本人", "空白", "待定", "另附", "详见",
                   "同意", "确认", "委托", "授权", "身份证", "联系", "姓名", "职务"}


def find_legal_reps(text):
    """返回 [(start, end, 姓名, 角色)]，只在「法定代表人：X」这类签署语境命中。"""
    out = []
    for m in _FADA_PAT.finditer(text or ""):
        name = m.group("name")
        if name in _FADA_BLACKLIST:
            continue
        # 已经是化名（「周某」）就不再脱——否则第二遍会把「周某」当成真名再脱一次，
        # 映射表里出现「周某→周某」这种自反记录。
        if "某" in name:
            continue
        try:
            import chinese_names as _C
            if not _C.looks_like_name(name):
                continue
            if not _C.split_surname(name)[0]:
                continue
        except Exception:
            continue
        out.append((m.start("name"), m.end("name"), name, m.group("role")))
    return out


def party_companies(text):
    """识别「甲方：XX有限公司」这类主体配对，返回 ({公司全称: 角色占位符}, {角色: 公司全称})。

    民事模式的核心：公司名脱成「[甲方公司]」「[乙方公司]」而不是「[公司1]」，
    这样脱敏后 AI 读起来仍然知道谁是谁，合同的权利义务对应关系不丢。
    """
    co2role, role2co = {}, {}
    for m in _PARTY_PAT.finditer(text or ""):
        role = m.group("role")
        # 「发包人（甲方）：XX公司」——合同全文说的是「甲方」，占位符也应叫甲方公司，
        # 否则成品里冒出一个「发包人公司」，读者对不上正文的「甲方」。
        note = m.group("note") or ""
        for cand in ("甲方", "乙方", "丙方", "丁方"):
            if cand in note:
                role = cand
                break
        co = m.group("co").strip()
        co = re.sub(r"^(?:与|及|和|或|向|由|经|该|本|的)+", "", co)
        if len(co) < 5:
            continue
        core = re.sub(_CO_SUFFIX_TXT, "", co).strip("（）()")
        if len(core) < 2:
            continue
        co2role.setdefault(co, role + "公司")
        role2co.setdefault(role, co)
    return co2role, role2co


