                _phs = [self._placeholder(_nm, "[地址]", "地址") for _a, _b, _nm in _sp]
                for (_a, _b, _nm), _ph in reversed(list(zip(_sp, _phs))):
                    _tk = "%s%d%s" % (self._G0, len(tokens), self._G1)
                    tokens.append((_tk, _ph))
