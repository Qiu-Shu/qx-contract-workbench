def _org_lead_prefix(val):
    """机构串里「机构类型词」之前的那一段（没有类型词就返回空串）。"""
    try:
        import org_short
    except Exception:
        return ""
    pos = len(val)
    for _w, _s, _lv in sorted(org_short.ORG_TYPES, key=lambda t: -len(t[0])):
        i = val.find(_w)
        if 0 <= i < pos:
            pos = i
    return val[:pos]


def _strip_bad_lead(val, category):
    """机构正则往前多吃了角色词/伪人名时，返回「噪声长度」，由调用方保留原文。

    2026-10-27 实测（用户报错连带）：「被告人时任香格里拉市公安局」整串命中，
    旧实现在字符串上删字再替换，把「告人」从成品里删掉了，
    句子变成「被市公安局副局长张某到案」——人没了，话也不通。

    现在只算 n，不动字：调用方拼成「原文前 n 字 + 简写」，
    输出是「被告人时任市公安局副局长张某到案」，读得通、地名照脱。

    两条硬约束（防止把地名当噪声削掉）：
      ① 剥完剩下的部分必须还含机构类型词（局/院/所/厅/部/委/办…）；
      ② 剥掉的部分里必须有一个完整的多字噪声词（时任/被告/本人…），
         光靠「长」「和」这类单字不算——否则「长沙市中级人民法院」会变成
         「沙市中级人民法院」，「共和县人民法院」会变成「和县人民法院」。
    """
    if category not in _ORG_SHORT_CATS or not val:
        return 0, val
    n = 0
    while n < len(val) - 4 and n < 5 and val[n] in _LEAD_NOISE_CHARS:
        n += 1
    if not n:
        return 0, val
    head, tail = val[:n], val[n:]
    if not any(k in tail for k in _ORG_TAIL_MARKS):
        return 0, val
    if not any(w in head for w in _LEAD_NOISE_WORDS):
        return 0, val
    return n, tail




def _ok_person(name, strong=False):
    """角色词后面捞到的 2-4 字，够不够格当人名。

    strong=True 表示有明确角色词托底（「被告人高明」），此时允许突破
    「常用词排除表」——「高明」当形容词时不是人名，当被告人时是人名，
    这正是用户要求的「同一个词在不同语境要不同处理」。
    但即使有角色词托底，程序词（陈述/供述/辩解…）仍然一律不认。
    """
    try:
        import chinese_names as C
    except Exception:
        return False
    if not (2 <= len(name) <= 4):
        return False
    # 末尾是虚词/动词的，一定是截断了（2026-11-02 实测：
    # 「被告人张三、张四以非法占有为目的」被切成「张四以」，成品变成
    # 「张某丙非法占有为目的」——一个"以"字被吃掉，句子读不通，
    # 还凭空多出第三个当事人）。这类字几乎不会出现在名字末尾。
    if name and name[-1] in "以为的系在与将向从被由及等伙又还并而则其该此所于对给把就都也已未不没让使令":
        return False
    # 已经是化名（杨某某/X某）就不要再动，否则「杨某某」会被抹成「杨某」
    if "某" in name or "X" in name or "x" in name:
        return False
    # 「甲方某某公司…」：武 是姓，武汉 是地名，别把地名化成人名
    if any(p and name.startswith(p) for p in C.PLACE_PREFIX):
        return False
    if any(w in name for w in _PERSON_BAN):
        return False
    if name in _PROC_WORDS:
        return False
    # 程序词按前缀判：「经批准」「关于遮」这种是从长词上截下来的碎片，
    # 整词比对永远命中不了（2026-10-27 实测「出卖人经批准，在…」被脱成「经某」）。
    if any(name.startswith(w) for w in _PROC_WORDS):
        return False
    # 泛称/栏名词不是人名（代理人/双方/各方…），见 _GENERIC_STOP 注释
    if name in _GENERIC_STOP or name in _NAME_FIELD_WORDS:
        return False
    # 角色词自己不是人名。实测「原告汪忠志与被告江山、第三人刘存程到庭」：
    # 顿号连排入口把「第三人」当成列表里的第二个人，脱成「原告汪某与被告江某、
    # 第某刘某」——角色词被肢解，句子看不懂。
    if name in C.ROLE_WORDS or name in _EXTRA_ROLES:
        return False
    if len(name) >= 2 and name[:2] in _GENERIC_PREFIX2:
        return False
    # 姓名栏词（曾用名/别名/化名…）自己不是姓名，被当成人名会脱成「曾某」
    if any(name.endswith(w) for w in _NAME_FIELD_WORDS):
        return False
    # 合同一方泛称不是人名：「出卖人向乙方支付」曾被脱成「向某方」——
    # 向 是姓、乙方 是两个字，结构上和真名没区别，只能按「甲乙丙丁+方」否掉。
    if len(name) >= 3 and name[1] in "甲乙丙丁" and name[2] == "方":
        return False
    # 序数/条款序号不是人名。「第一章」「第二条」「第一被告」里的「第」是姓、
    # 「一/二」是名，结构上和真名一模一样，只能按「第」开头一律否掉。
    # 「第五」虽是复姓，实务文书里 99.9% 是序号，宁可漏一个极端生僻姓也不能
    # 把合同目录脱成「第一章 合同当事人第某 商品」（2026-10-27 旧语料实测）。
    if name[0] == "第":
        return False
    sur, given = C.split_surname(name)
    if not sur or not given:
        return False
    if any(ch in "局院所厅部委办站队科处室号条项款元角分年月日" for ch in given):
        return False
    # 右边界：真实姓名的末字不会是连词/虚词。「被告江山与原告…」曾把「与」
    # 一起吞进姓名（江山与 → 江某），句子就断了。
    if name[-1] in "与及或等将对向为在是并的着过到":
        return False
    # 三字以上且后两字全是虚词（都有以/双方意）：不是名字
    if len(name) >= 3 and name[-1] in _FUNC_CHARS and name[-2] in _FUNC_CHARS:
        return False
    # 角色词后接的是动作词（乙方应当/债权人支付/保证人解除合同），不是姓名
    if name in _ROLE_VERB_STOP or name[:2] in _ROLE_VERB_STOP:
        return False
    # 伪人名清单：时任/现任/案发/现场…（时 是姓、任 是名，结构上跟真名没区别，
    # 只能靠清单收口）。整词命中或前两字命中都否决。
    if name in _PSEUDO_NAMES or name[:2] in _PSEUDO_NAMES:
        return False
    # 价款术语不是姓名：Han 2026-10-27 实测「包税价」被切成「包某」——
    # 「包」正好是姓，「税价」被当名字。价/税/费/率/额/元/息 这些字
    # 在真实姓名里几乎不出现，出现在角色词后面一定是钱的事。
    if any(ch in "价税费率额元息" for ch in name):
        return False
    if strong:
        # 两字名 + 兼作虚词的姓氏（和/于/从/何…）：无角色词时一律不认，
        # 有角色词时也只有三字以上才认，避免「被告人何某」被过度推断
        if len(name) == 2 and sur in C.FUNCTION_SURNAMES:
            return False
        return True
    return bool(C.looks_like_name(name, strict=True))


