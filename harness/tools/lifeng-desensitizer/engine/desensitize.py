    def prescan(self, full_text):
        """先扫全文：人名、甲乙方公司、字号回指，都在这里定下来。

        为什么人名必须全文预扫（2026-11-02 修）：
            原来只在「角色词附近」认人，逐段调用时每段各扫各的，
            于是第 1 段认出的「张三」，到第 5 段「张三与张四系兄弟」里
            就不再是"已确认的人名"，原样留在成品里——同一份文书里
            主角名字漏脱，比整篇没脱更危险（看着像脱过了）。
        为什么同姓要按甲乙丙编号：
            两个不同的人共用一个「张某」，还原时只能还原成其中一个
            （映射是 占位符→原值 的单值结构），另一个当事人的名字就永远回不来了。
            「张某2」这种数字后缀又像条款编号，改成「张某甲／张某乙」既唯一又能读。
        """
        if not full_text:
            return
        # ⚡ 2026-11-06 修「导了词表但假名不是自己写的那份」：
        # 必须**先**把词表里的词条登记进 _seen，再让 prescan 去扫人名。
        # 原来是反过来的：_prescan_names 抢先给「某某某」起了「王某」，
        # 等到 redact_text 步骤 1 走词表时，_placeholder 一看 orig 已在 _seen
        # 就直接返回「王某」，词表里写的「王某涛」被静默丢掉 ——
        # 用户看到的现象就是「词表导进去了、界面也显示，但脱出来的名字不对味」。
        # 用户自己写下的假名是他明确要的，优先级高于结构规则自动起的。
        for _o, _r in (self.terms or []):
            if _o and _r:
                self._placeholder(_o, _r, "自定义词")
        self._prescan_names(full_text)
        if self.mode != "civil":
            return
        co2role, role2co = party_companies(full_text)
        # 同一角色出现多家公司时全部编号：乙方公司1 / 乙方公司2 / 乙方公司3。
        #
        # 不编号的后果（2026-10-30 实测）：尽调报告里 16 家不同的「乙方」公司
        # 共用一个 [乙方公司]，复原时只能还原成其中一家，其余 15 家全被替换成它，
        # 而且不报错——成品读起来依然是一份通顺的报告。这是最危险的一种错。
        #
        # 这里必须走 _placeholder()：直接 append 会绕过去重逻辑，
        # 「一个占位符只能指向一个原值」这条不变量就守不住了。
        by_role = {}
        for co, r in co2role.items():
            by_role.setdefault(r, []).append(co)
        fixed = {}
        for r, cos in by_role.items():
            if len(cos) == 1:
                self._placeholder(cos[0], "[%s]" % r, "主体公司")
                fixed[cos[0]] = r
            else:
                for i, co in enumerate(cos, 1):
                    pat = "%s%d" % (r, i)
                    self._placeholder(co, "[%s]" % pat, "主体公司")
                    fixed[co] = pat
        self._party_map = fixed
        self._party_rows = role2co

        # ---- 预扫字号回指（2026-10-28 修跨段失效）----
