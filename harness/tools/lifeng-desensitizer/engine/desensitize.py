def law_spans(text):
    """返回文本里「法规类名称」的区间列表（这些一律不替换）。

    双保险：结构正则 + 高频法规名清单。
    含经营主体通名的串不保护——例如《某某商贸有限公司采购合同》，
    书名号里装的是合同不是法规，里面的公司名照脱。

    ⚡ 2026-10-28 收口：原先只要套了《》就一律保护，等于**合同里所有书名号
    都是免疫区**——实测《远景科技园三期土建工程材料设备清单》《招标文件》
    《建设工程施工合同》《远景科技园三期土建工程施工合同》全部被判成法规，
    项目名、字号、附件名原样留在成品里。合同类文书恰恰通篇是《》，
    这个洞比想象的大得多。
    现在《》里必须**以法规后缀收尾**（法/法典/条例/规定/办法/细则/解释…）
    或本身在高频法规名清单内，才保护；清单/合同/图纸/招标文件一概不保护。
    """
    if not text:
        return []
    spans = []
    for m in _LAW_PAT.finditer(text):
        seg = m.group(0)
        core = seg.strip("《》")
        if any(w in core for w in _LAW_BIZ):
            continue
        if seg.startswith("《"):
            # 只认真正的法规名：剥掉尾部括号（（一）、（2020修正））后看后缀
            base = _LAW_TAIL_SUB.sub("", core).strip()
            if not (base in _LAW_NAMES or base.endswith(_LAW_TAIL)):
                continue          # 书名号里不是法规 → 交给脱敏规则
        spans.append((m.start(), m.end()))
    for name in _LAW_NAMES:
        start = 0
        while True:
            i = text.find(name, start)
            if i < 0:
                break
            start = i + 1
            # 「有限公司法定代表人」里的「公司法」不是法规名 —— 放过去就会
            # 把公司名从中间劈开，导致整条公司名匹配不上、真名漏脱。
            if text[max(0, i - 2):i] in ("有限", "股份", "责任", "分", "子"):
                continue
            spans.append((i, i + len(name)))
    if not spans:
        return []
    # 合并重叠，按起点排序
    spans.sort()
    merged = [list(spans[0])]
    for a, b in spans[1:]:
        if a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return [(a, b) for a, b in merged]


def is_law_name(text):
    """整条词是否就是法规名（用于识敏阶段拒绝把法规名收进词表）。"""
    if not text or len(text) > 90:
        return False
    t = text.strip().strip("《》")
    # 精确清单优先：「公司法」本身是法规名，不该因为含「公司」被否掉
    if t in _LAW_NAMES:
        return True
    if any(w in t for w in _LAW_BIZ):
        return False
    return bool(re.fullmatch(
        r"(?:中华人民共和国)?[\u4e00-\u9fa5]{0,20}"
        r"(?:法典|法|条例|实施细则|实施办法|暂行办法|办法|规定|细则|通则|解释)",
        t)) and len(t) <= 40


