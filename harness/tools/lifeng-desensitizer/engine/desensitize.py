def _cell_text(cell):
    """单元格纯文本（含全部段落）。"""
    try:
        return "\n".join(_para_wt_text(p) for p in cell.paragraphs).strip()
    except Exception:
        return (cell.text or "").strip()


def _norm_field(s):
    """栏位名归一：去空白、冒号、括号，便于和映射表比对。"""
    return re.sub(r"[\s:：()（）\[\]【】、,，]", "", s or "")


def _field_category(text):
    return _TABLE_FIELD_CATS.get(_norm_field(text))


def _redact_cell_value(cell, category, redactor):
    """把整格的值当成该栏位的一个完整值脱掉。

    已经是占位符（带方括号）的不动 —— 那是前面自动规则已经处理过的，
    再脱一遍会变成「[合同编号]」套「[合同编号2]」。
    """
    from docx.oxml.ns import qn
    # 规则面板里关掉这个类别就不脱 —— 用户在配置里关过它就该听他的
    try:
        if not redactor._on(category):
            return 0
    except Exception:
        pass
    changed = 0
    for p in cell.paragraphs:
        txt = _para_wt_text(p)
        if not txt or not txt.strip():
            continue
        if "[" in txt and "]" in txt:
            continue
        if _has_structure(p):
            continue
        ph = redactor._placeholder(txt.strip(), None, category)
        if not ph or ph == txt.strip():
            continue
        wt = list(p._p.iter(qn('w:t')))
        if not wt:
            try:
                p.add_run(ph)
                changed += 1
            except Exception:
                pass
            continue
        # 保留第一个文本节点的格式，其余清空：表格里的值一般格式统一，
        # 这样能把「跨 run 拆开的编号」一次性收拢成一个占位符。
        wt[0].text = ph
        try:
            wt[0].set(qn('xml:space'), 'preserve')
        except Exception:
            pass
        for t in wt[1:]:
            t.text = ""
        changed += 1
    return changed


def redact_tables(doc, redactor):
    """表格脱敏：先按「表头列」配对，再按「同行相邻」配对。

    两种排版都要管：
      ① 表头一行写栏位名，下面每行是值（合同最常见的样式）；
      ② 一行里「栏位名 | 值」并排（登记表样式）。
    """
    total = 0
    for tbl in doc.tables:
        rows = list(tbl.rows)
        if not rows:
            continue

        # ---- ① 找表头行（前 3 行里，至少 2 格是已知栏位名）----
        head_i = -1
        col_cat = {}
        for i, row in enumerate(rows[:3]):
            m = {}
            for ci, cell in enumerate(row.cells):
                c = _field_category(_cell_text(cell))
                if c:
                    m[ci] = c
            # 栏位名至少 2 个才当表头，避免单格表格误判
            if len(m) >= 2:
                head_i, col_cat = i, m
                break

        if head_i >= 0:
            for row in rows[head_i + 1:]:
                cells = list(row.cells)
                for ci, cat in col_cat.items():
                    if ci < len(cells):
                        total += _redact_cell_value(cells[ci], cat, redactor)

        # ---- ② 同行相邻配对（跳过表头行本身）----
        for ri, row in enumerate(rows):
            if ri == head_i:
                continue
            cells = list(row.cells)
            for ci, cell in enumerate(cells):
                cat = _field_category(_cell_text(cell))
                if not cat:
                    continue
                for cj in range(ci + 1, len(cells)):
                    v = _cell_text(cells[cj])
                    if not v:
                        continue
                    if v.startswith("[") and v.endswith("]"):
                        break
                    total += _redact_cell_value(cells[cj], cat, redactor)
                    break
    return total


def redact_all_text_nodes(doc, redactor):
    """兜底：遍历全部 w:t 文本节点（含文本框/形状内文字），确保无遗漏。"""
    from docx.oxml.ns import qn
    roots = [doc.element.body]
    for section in doc.sections:
        for hf in (section.header, section.footer,
                   section.first_page_header, section.first_page_footer,
                   section.even_page_header, section.even_page_footer):
            try:
                if hf is not None:
                    roots.append(hf._element)
            except Exception:
                continue
    for root in roots:
        for t in root.iter(qn('w:t')):
            if t.text:
                t.text = redactor.redact_text(t.text)


def clear_core_props(doc):
    cp = doc.core_properties
    for attr in ("author", "last_modified_by", "title", "subject", "category",
                 "comments", "content_status", "identifier", "keywords", "language", "version"):
        try:
            setattr(cp, attr, "")
        except Exception:
            pass


def iter_hf_paragraphs(doc):
    for section in doc.sections:
        for hf in (section.header, section.footer,
                   section.first_page_header, section.first_page_footer,
                   section.even_page_header, section.even_page_footer):
            try:
                if hf is None:
                    continue
                for p in hf.paragraphs:
                    yield p
                for tbl in hf.tables:
                    for row in tbl.rows:
                        for cell in row.cells:
                            for p in cell.paragraphs:
                                yield p
            except Exception:
                continue


def _docx_full_text(doc):
    """把整篇 docx 的文字拼起来（正文 + 表格 + 页眉页脚），供 prescan 使用。"""
    from docx.oxml.ns import qn
    parts = []
    for p in doc.paragraphs:
        parts.append(_para_wt_text(p))
    for tbl in doc.tables:
        for row in tbl.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    parts.append(_para_wt_text(p))
    for p in iter_hf_paragraphs(doc):
        parts.append(_para_wt_text(p))
    try:
        for t in doc.element.body.iter(qn('w:t')):
            if t.text:
                parts.append(t.text)
    except Exception:
        pass
    return "\n".join(parts)


def redact_docx(in_path, out_path, redactor):
    from docx import Document
    doc = Document(in_path)
    # 民事模式必须先扫全文：甲乙方抬头在第一页，正文却在后面反复提同一家公司
    redactor.prescan(_docx_full_text(doc))
    for p in doc.paragraphs:
        redact_paragraph(p, redactor)
    for tbl in doc.tables:
        for row in tbl.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    redact_paragraph(p, redactor)
    # 2026-11-06：逐段落跑完再补表格配对。
    # 带锚点的规则（合同编号/身份证号/银行账号…）跨不过单元格，
    # 表格里「栏位名 | 值」分列的编号只能靠这一步兜住。
    try:
        redact_tables(doc, redactor)
    except Exception:
        pass
    for p in iter_hf_paragraphs(doc):
        redact_paragraph(p, redactor)
    redact_all_text_nodes(doc, redactor)  # 兜底：文本框/形状内文字
    clear_core_props(doc)
    doc.save(out_path)


def redact_plain(in_path, out_path, redactor):
    with open(in_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()
    redactor.prescan(content)
    content = redactor.redact_text(content)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)


def verify_docx(path, redactor):
    """体检：重开成品扫描残留。返回残留列表。"""
    from docx import Document
    doc = Document(path)
    leftovers = []
    for p in doc.paragraphs:
        leftovers.extend(redactor.residual(p.text))
    for tbl in doc.tables:
        for row in tbl.rows:
            for cell in row.cells:
                leftovers.extend(redactor.residual(cell.text))
    for p in iter_hf_paragraphs(doc):
        leftovers.extend(redactor.residual(p.text))
    # 兜底：文本框/形状内文字
    from docx.oxml.ns import qn
    roots = [doc.element.body]
    for section in doc.sections:
        for hf in (section.header, section.footer,
                   section.first_page_header, section.first_page_footer,
                   section.even_page_header, section.even_page_footer):
            try:
                if hf is not None:
                    roots.append(hf._element)
            except Exception:
                continue
    for root in roots:
        for t in root.iter(qn('w:t')):
            if t.text:
                leftovers.extend(redactor.residual(t.text))
    return leftovers


