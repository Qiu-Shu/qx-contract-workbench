def disabled_spans(text):
    """返回被禁用字段在文本中的命中区段 [(起点, 终点), ...]。"""
    out = []
    for p in _disabled_regexes():
        try:
            rx = re.compile(p)
        except Exception:
            continue
        for m in rx.finditer(text or ""):
            out.append((m.start(), m.end()))
    return out


def in_disabled(start, end, spans):
    """命中区段是否落在某个禁用区段内（用于跳过冒名顶替的匹配）。"""
    for s, e in spans:
        if s <= start and end <= e:
            return True
    return False


def protect_disabled_spans(text, tag="K"):
    """把禁用字段的命中片段换成哨兵，返回 (保护后文本, [(哨兵, 原文)])。

    给表格通道用：它靠 rx.sub 做整体替换，没有位置概念，
    只能先把不该动的片段换走，替换完再还原。
    """
    pairs = []
    for p in _disabled_regexes():
        try:
            rx = re.compile(p)
        except Exception:
            continue

        def _rep(m):
            tk = "\x01%s%d\x02" % (tag, len(pairs))
            pairs.append((tk, m.group(0)))
            return tk

        text = rx.sub(_rep, text)
    return text, pairs


def restore_spans(text, pairs):
    for tk, orig in pairs:
        text = text.replace(tk, orig)
    return text
