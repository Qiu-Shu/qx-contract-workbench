def _co_core(name):
    """剥行政区划与组织形式，得到含行业词的「准字号」。

    湖北远景科技园开发有限公司 → 远景科技园开发
    武汉长江存储科技有限责任公司 → 长江存储科技
    """
    s = _ZI_SUFFIX.sub("", (name or "").strip())
    if len(s) < 2:
        return ""
    for _ in range(4):
        hit = next((p for p in _ADM_BARE if s.startswith(p) and len(s) - len(p) >= 2), None)
        if hit:
            s = s[len(hit):]
            continue
        m = _ADM_SUFFIX.match(s)
        if m and len(s) - len(m.group(0)) >= 2:
            s = s[m.end():]
            continue
        break
    return s if len(s) >= 2 else ""


def _is_pure_industry(s):
    """整串是否全由行业词拼成（「建设工程」= 建设+工程）。

    这类串绝不能当字号——否则「宏基建设工程有限公司」会把全篇
    「建设工程施工合同」的「建设工程」当回指脱掉，标题变「[字号2]施工合同」。
    真实踩过的坑。
    """
    t, changed = s, True
    while t and changed:
        changed = False
        for w in _INDUSTRY_TAIL:
            if t.startswith(w):
                t = t[len(w):]
                changed = True
                break
    return t == ""


def _zi_candidates(core):
    """从准字号派生候选：剥行业尾 + 剥地名前缀，长的在前。

    ⚡ 2026-10-28 补「剥地名前缀」（示例合同实测出的真缺陷）：
      `_ADM_BARE` 是硬编码词表，遇到词表外地名（如虚构的「江城」）剥不掉，
      core 成了「江城远景科技园开发」，而正文写的是「远景科技园三期土建工程」，
      最长前缀法一个都匹配不上，字号回指整个失效。

      补法：对**已剥掉行业尾的形态**再试剥前 2–4 字（地名词典型长度）。
      只对剥过行业尾的形态做——对原始 core 乱剥会产出「设工程」这类
      半截行业词，反而把正文咬花。

      ⚡ 同时排除纯行业词：「宏基建设工程」的后缀「建设工程」必须挡掉。
    """
    out, s = [], core
    for _ in range(3):
        hit = next((w for w in _INDUSTRY_TAIL if s.endswith(w) and len(s) - len(w) >= 2), None)
        if not hit:
            break
        s = s[: -len(hit)]
        out.append(s)
    stripped = list(out)          # 已剥行业尾的形态
    out.append(core)
    base = [c for c in out if len(c) >= 3 and not _is_pure_industry(c)]
    # 只对剥过行业尾的形态剥地名前缀（2–4 字）
    extra = []
    for c in stripped:
        for i in range(2, min(4, len(c) - 2) + 1):
            cand = c[i:]
            if len(cand) >= 3 and not _is_pure_industry(cand):
                extra.append(cand)
    return sorted({c for c in base + extra if len(c) >= 3}, key=len, reverse=True)


def _pick_zi(name, masked_text, min_len=2):
    """在「公司全称已换成哨兵」的正文里，挑真正独立出现的字号（最长优先）。

    关键：此时公司全称已是哨兵，正文里再出现「远景科技园」只可能来自
    项目名/附件名/地址等**独立回指**——这正是要脱的东西。
    通用词（_ZI_BAN）一律不选，宁漏不误伤。
    """
    core = _co_core(name)
    if not core:
        return ""
    for cand in _zi_candidates(core):
        if cand in _ZI_BAN:
            continue
        if len(cand) >= min_len and cand in masked_text:
            return cand
    return ""


def _project_name_spans(text):
    """识别「工程名称：XXX」这类栏位值，返回 [(start, end, 值)]。

    只认有明确栏位名的，不做正文推测——正文里的项目名由字号层处理。
    """
    out = []
    for m in _PROJECT_NAME_FIELD.finditer(text):
        v = m.group(1).strip(" 　:：")
        if len(v) < 2:
            continue
        # 已经是占位符的不重复处理
        if v.startswith("[") and v.endswith("]"):
            continue
        a = m.start(1) + (len(m.group(1)) - len(m.group(1).lstrip(" 　:：")))
        out.append((a, a + len(v), v))
    return out


