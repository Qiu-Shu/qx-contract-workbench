def main():
    if (ROOT / 'config/skill-repair-freeze.json').exists():
        raise SystemExit('Reviewed batch is frozen; refusing to overwrite final adapters.')
    items = json.loads(GROUP.read_text(encoding='utf-8-sig'))
    assert len(items) == 31 and len({i['name'] for i in items}) == 31
    assert len(SPECS) == 23
    changes = []
    for item in items:
        name = item['name']
        path = ROOT / 'workspace/.dsh/skills' / name / 'SKILL.md'
        before = ROOT / 'docs/checks/skills-repair/before' / name / 'SKILL.md'
        baseline = json.loads((ROOT / item['response']).read_text(encoding='utf-8-sig'))
        assert baseline['response'] and item['evidence']
        text, action, reason, replacement, checks = build(item)
        assert text.startswith(f'---\nname: {name}\n')
        assert '~/.claude' not in text and '[法条原文]' not in text
        assert not re.search(r'第[0-9一二三四五六七八九十]+条', text)
        for target in re.findall(r'\]\(([^)]+)\)', text):
            assert (path.parent / target).resolve().is_file(), (name, target)
        if path.read_text(encoding='utf-8') != text:
            path.write_text(text, encoding='utf-8', newline='\n')
        record = dict(name=name, action=action, reason=reason,
                      beforeSha256=sha(before.read_bytes()), afterSha256=sha(path.read_bytes()),
                      criticalChecks=checks)
        if replacement:
            record['replacement'] = replacement
        changes.append(record)
    out = ROOT / 'docs/checks/skills-repair/group-a-changes.json'
    out.write_text(json.dumps(changes, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    write_scenarios(items)
    print(json.dumps({'count': len(changes), 'repair': sum(c['action']=='repair' for c in changes),
                      'merge': sum(c['action']=='merge' for c in changes), 'static_checks': 'passed'}, ensure_ascii=False))

if __name__ == '__main__':
    main()
