def sha(data):
    return hashlib.sha256(data).hexdigest()

def main():
    if (ROOT / 'config/skill-repair-freeze.json').exists():
        raise SystemExit('Reviewed batch is frozen; refusing to overwrite final adapters.')
    assert len(ITEMS) == len(SPECS) == 27
    assert {x['name'] for x in ITEMS} == set(SPECS)
    for item in ITEMS:
        existing = ROOT / 'workspace/.dsh/skills' / item['name'] / 'SKILL.md'
        if existing.exists() and '<!-- group-b-one-repair-after-round1 -->' in existing.read_text(encoding='utf-8'):
            raise SystemExit('Round-2 repair already exists; refusing to overwrite verified later work.')
    changes = []
    for item in ITEMS:
        name = item['name']
        entry = SPECS[name]
        backup = ROOT / 'docs/checks/skills-repair/before' / name / 'SKILL.md'
        baseline = ROOT / item['response']
        assert backup.is_file() and baseline.is_file(), name
        observed = json.loads(baseline.read_text(encoding='utf-8-sig'))
        assert observed.get('response') and item.get('evidence'), name
        text = f'---\nname: {name}\ndescription: {json.dumps(entry["description"], ensure_ascii=False)}\n---\n\n# {item["chineseName"]}\n\n<!-- workbench-skill-repair-v2 -->\n<!-- legal-quality-v2-structural -->\n\n'
        text += BOUNDARY + '\n' + entry['body'] + '\n\n'
        if entry['contract']:
            text += CONTRACT + '\n'
        if entry['employment']:
            text += EMPLOYMENT + '\n'
        if entry['dates']:
            text += DATES + '\n'
        text += '## 来源与交付核对\n\n原始中英文库及许可证保留在 `legal-library/zh/` 与 `legal-library/en/`；本文件是工作台修订适配层，不把原库默认规则升级为本次证据。逐项核对输出的事实、状态、数值和替代分支是否都有输入或已核来源；未执行操作明确标为草稿/方案。\n'
        assert re.match(r'^---\nname: [a-z0-9-]+\ndescription: "Use when ', text)
        assert '~/.claude' not in text and '[法条原文]' not in text
        dest = ROOT / 'workspace/.dsh/skills' / name / 'SKILL.md'
        dest.write_text(text, encoding='utf-8', newline='\n')
        changes.append(dict(name=name, action=entry['action'], reason=item['note'],
                            **({'replacement': entry['replacement']} if entry['replacement'] else {}),
                            beforeSha256=sha(backup.read_bytes()), afterSha256=sha(dest.read_bytes()),
                            criticalChecks=entry['checks']))
    (ROOT / 'docs/checks/skills-repair/group-b-changes.json').write_text(
        json.dumps(changes, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Rebuilt and structurally checked {len(changes)} assigned adapters.')

if __name__ == '__main__':
    main()
